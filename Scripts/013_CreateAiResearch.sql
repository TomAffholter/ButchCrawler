IF OBJECT_ID(N'dbo.AiAnalyses',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.AiAnalyses(
  Id BIGINT IDENTITY(1,1) NOT NULL CONSTRAINT PK_AiAnalyses PRIMARY KEY,
  Task NVARCHAR(32) NOT NULL, Source NVARCHAR(2000) NOT NULL, SourceHash BINARY(32) NOT NULL,
  InputHash BINARY(32) NOT NULL, Model NVARCHAR(128) NOT NULL,
  OutputText NVARCHAR(MAX) NOT NULL, ResultJson NVARCHAR(MAX) NOT NULL,
  Reviewed BIT NOT NULL CONSTRAINT DF_AiAnalyses_Reviewed DEFAULT 0,
  ReviewedText NVARCHAR(MAX) NULL, ReviewedAtUtc DATETIME2 NULL,
  CreatedAtUtc DATETIME2 NOT NULL CONSTRAINT DF_AiAnalyses_Created DEFAULT SYSUTCDATETIME(),
  CONSTRAINT UX_AiAnalyses_Cache UNIQUE(Task,SourceHash,InputHash,Model));
END;
